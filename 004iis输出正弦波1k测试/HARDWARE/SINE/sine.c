#define PI              3.1415926f  	//圆周率
#define SINE_AMPLITUDE  24000.0f    	//正弦波幅度(16位数据,最大幅度为32767)

u16 sine_tbl[SINE_TABLE_SIZE];      	//正弦波数据表

//生成500Hz正弦波数据表
//采样率48KHz,数据表96个采样点含1个正弦周期,则输出频率=48000*1/96=500Hz
//每个采样点存放两次,分别作为左/右声道数据
void sine_tbl_init(void)
{
    u16 i;
    s16 temp;

    for(i=0;i<SINE_TABLE_SIZE/2;i++)//计算96个正弦采样点(含1个完整周期)
    {
        temp=(s16)(SINE_AMPLITUDE*sinf(2*PI*SINE_TABLE_PERIODS*i/(SINE_TABLE_SIZE/2)));//计算正弦采样值
        sine_tbl[2*i]=(u16)temp;    //左声道数据
        sine_tbl[2*i+1]=(u16)temp;  //右声道数据
    }
}

